#!/usr/bin/env python3
"""Writes ogsim/unitdata.py: ships and defence of the game (price, requirements, hull, shield, attack, speed, cargo, fuel,
rapid fire, speed upgrades), read from the game's own PHP source so the fast simulator cannot drift from the game.

    python gen_unitdata.py                 (reads ../app/GameObjects, writes ogsim/unitdata.py)
    python gen_unitdata.py --check         (exit 1 when the committed file differs from the PHP source)
"""
from __future__ import annotations

import argparse
import pprint
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SOURCES = {"ship": ("CivilShipObjects.php", "MilitaryShipObjects.php"), "defense": ("DefenseObjects.php",)}
NAME = re.compile(r"->machine_name\s*=\s*'([a-z_]+)'")
PRICE = re.compile(r"new GameObjectPrice\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)")
REQ = re.compile(r"new GameObjectRequirement\(\s*'([a-z_]+)'\s*,\s*(\d+)\s*\)")
RAPID = re.compile(r"new GameObjectRapidfire\(\s*'([a-z_]+)'\s*,\s*(\d+)\s*\)")
PROPS = re.compile(r"new GameObjectProperties\(\s*\$\w+\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*\d+\s*)?\)")
UPGRADE = re.compile(r"new GameObjectSpeedUpgrade\(\s*'([a-z_]+)'\s*,\s*(\d+)\s*(?:,\s*(\d+))?\s*\)")


def section(block: str, key: str) -> str:
    if key not in block:
        return ""
    part = block[block.index(key):]
    return part[:part.index("];")] if "];" in part else part


def parse(text: str, kind: str) -> dict[str, dict]:
    out: dict[str, dict] = {}
    marks = [(m.start(), m.group(1)) for m in NAME.finditer(text)]
    for i, (pos, name) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(text)
        block = text[pos:end]
        price, props = PRICE.search(block), PROPS.search(block)
        if not price or not props:
            continue
        hull, shield, attack, speed, cargo, fuel = (int(x) for x in props.groups())
        out[name] = {
            "kind": kind, "metal": int(price.group(1)), "crystal": int(price.group(2)), "deuterium": int(price.group(3)),
            "requires": {n: int(v) for n, v in REQ.findall(section(block, "->requirements"))},
            "rapid": {n: int(v) for n, v in RAPID.findall(section(block, "->rapidfire"))},
            "hull": hull, "shield": shield, "attack": attack, "speed": speed, "cargo": cargo, "fuel": fuel,
            "upgrades": [(n, int(lvl), int(sp) if sp else None) for n, lvl, sp in UPGRADE.findall(section(block, "->speed_upgrade"))],
        }
    return out


def build(src: Path) -> dict[str, dict]:
    data: dict[str, dict] = {}
    for kind, files in SOURCES.items():
        for f in files:
            data.update(parse((src / f).read_text(encoding="utf-8"), kind))
    return data


def render(data: dict[str, dict]) -> str:
    return ('"""Ships and defence of the game. GENERATED by gen_unitdata.py from app/GameObjects/*.php: do not edit by hand."""\n'
            f"UNITS = {pprint.pformat(data, width=140, sort_dicts=True)}\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default="/home/claude/work/wt-speed/app/GameObjects", help="app/GameObjects of the OGameX source")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(build(Path(args.src)))
    target = HERE / "ogsim" / "unitdata.py"
    if args.check:
        same = target.exists() and target.read_text(encoding="utf-8") == text
        print("unitdata.py is up to date" if same else "unitdata.py differs from the game source: run gen_unitdata.py")
        return 0 if same else 1
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
